// Click-through of the admin flows (CLAUDE.md §2). Real login; Analyze makes one real Claude call at 1440.
// Usage: node scripts/check-ui-flows.mjs <baseUrl>   (ADMIN_PASSWORD from .env.local or the environment)
import { createRequire } from "node:module";
import { tmpdir } from "node:os";
import { join } from "node:path";

const { chromium } = createRequire("C:/Users/Kasutaja/.claude/scripts/")("playwright");

try { process.loadEnvFile(".env.local"); } catch {}
const BASE = (process.argv[2] || process.env.BASE || "http://localhost:3000").replace(/\/$/, "");
const PASSWORD = process.env.ADMIN_PASSWORD;
if (!PASSWORD) { console.error("ADMIN_PASSWORD not set"); process.exit(1); }
// A news listing with no RSS at the URL or the common feed paths, so Analyze falls through to Claude.
const NO_RSS_PAGE = "https://digital-strategy.ec.europa.eu/en/news";

let failed = 0;
async function step(name, fn) {
  try { await fn(); console.log(`PASS ${name}`); }
  catch (e) { failed++; console.log(`FAIL ${name}: ${e.message.split("\n")[0]}`); }
}

const browser = await chromium.launch();
for (const width of [375, 1440]) {
  const page = await browser.newPage({ viewport: { width, height: width === 375 ? 812 : 900 } });
  const errors = [];
  page.on("pageerror", (e) => errors.push(e.message));

  await step(`${width}: admin login`, async () => {
    await page.goto(`${BASE}/admin/login`);
    await page.getByPlaceholder("Password").fill(PASSWORD);
    await page.getByRole("button", { name: "Sign in" }).click();
    await page.waitForURL((u) => !u.pathname.startsWith("/admin/login"), { timeout: 15000 });
  });
  await step(`${width}: Add source form opens`, async () => {
    await page.goto(`${BASE}/admin/sources/new`);
    await page.getByPlaceholder("https://example.com/news").waitFor();
  });
  if (width === 1440) {
    await step("1440: Analyze a page without RSS → AI-generated selectors", async () => {
      await page.getByPlaceholder("https://example.com/news").fill(NO_RSS_PAGE);
      const addAnyway = page.getByRole("button", { name: "Add anyway" });
      if (await addAnyway.isVisible()) await addAnyway.click();
      await page.getByRole("button", { name: "Analyze source" }).click();
      const ok = page.getByText("No RSS feed — CSS selectors generated by AI");
      const bad = page.getByText(/AI analysis failed/);
      await ok.or(bad).first().waitFor({ timeout: 180000 });
      if (await bad.isVisible()) throw new Error(await bad.innerText());
    });
  }

  await page.screenshot({ path: join(tmpdir(), `eudi-flows-${width}.png`) });
  if (errors.length) { failed++; console.log(`FAIL ${width}: page errors: ${errors.join(" | ")}`); }
  await page.close();
}
await browser.close();
console.log(failed ? `${failed} failed` : "all passed");
process.exit(failed ? 1 : 0);
